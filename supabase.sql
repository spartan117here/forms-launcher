-- 1. Create the `form_links` table
create table if not exists public.form_links (
    id bigint generated by default as identity primary key,
    title text,
    url text not null,
    created_at timestamptz default now() not null
);

-- 2. Enable Row Level Security (RLS) on `form_links`
alter table public.form_links enable row level security;

-- Drop existing policies if re-running script to avoid duplicate errors
drop policy if exists "Anyone can read form links" on public.form_links;
drop policy if exists "Authenticated users can insert form links" on public.form_links;
drop policy if exists "Authenticated users can update form links" on public.form_links;
drop policy if exists "Authenticated users can delete form links" on public.form_links;
drop policy if exists "Admin can insert form links" on public.form_links;
drop policy if exists "Admin can update form links" on public.form_links;
drop policy if exists "Admin can delete form links" on public.form_links;

-- 3. Policy: Anyone (anon public users and logged-in admins) can SELECT form links
create policy "Anyone can read form links"
on public.form_links
for select
to anon, authenticated
using (true);

-- 4. Policy: Only designated admin can INSERT new form links
create policy "Admin can insert form links"
on public.form_links
for insert
to authenticated
with check ((auth.jwt() ->> 'email') = 'spartan117here@gmail.com');

-- 5. Policy: Only designated admin can UPDATE form links
create policy "Admin can update form links"
on public.form_links
for update
to authenticated
using ((auth.jwt() ->> 'email') = 'spartan117here@gmail.com')
with check ((auth.jwt() ->> 'email') = 'spartan117here@gmail.com');

-- 6. Policy: Only designated admin can DELETE form links
create policy "Admin can delete form links"
on public.form_links
for delete
to authenticated
using ((auth.jwt() ->> 'email') = 'spartan117here@gmail.com');

-- 7. Performance Index for fast "order by created_at desc limit 1" queries
create index if not exists idx_form_links_created_at_desc
on public.form_links (created_at desc);

-- 8. Grant table permissions to anon and authenticated roles
grant select on table public.form_links to anon;
grant all privileges on table public.form_links to authenticated;

